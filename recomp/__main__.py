"""Recompile a DS game: python3 -m recomp <game.nds> -o <build dir> [--extra missing.txt] [--build]

Writes the C for both CPUs (gen/g9_*.c, gen/g7_*.c), the decompressed ARM9 image (arm9.bin)
and a Makefile that links them with the runtime into dsn_headless. --extra adds entry points
the runtime reported as missing (its missing.txt), for the next build.
"""
import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))

from nds import Rom, RomError     # noqa: E402
from .program import Program      # noqa: E402

MAKEFILE = """# generated by dsnative recomp
RT := {rt}
CC ?= cc
AR ?= ar
CFLAGS ?= -O2
override CFLAGS += -w -I$(RT)
GEN := $(sort $(wildcard gen/*.c))
RTSRC := $(filter-out $(RT)/main_%.c,$(wildcard $(RT)/*.c))
OBJ := $(GEN:.c=.o) $(patsubst $(RT)/%.c,rt_%.o,$(RTSRC))

dsn_headless: $(OBJ) rt_main_headless.o
\t$(CC) $(CFLAGS) -o $@ $^

# the game and the runtime without a driver, for an app to link
libdsn.a: $(OBJ)
\trm -f $@ && $(AR) rcs $@ $^

gen/%.o: gen/%.c $(RT)/dsr.h
\t$(CC) $(CFLAGS) -c -o $@ $<
rt_%.o: $(RT)/%.c $(wildcard $(RT)/*.h)
\t$(CC) $(CFLAGS) -c -o $@ $<

clean:
\trm -f $(OBJ) rt_main_headless.o dsn_headless libdsn.a
"""


def read_extra(path):
    out = {9: [], 7: []}
    if not path or not os.path.exists(path):
        return out
    with open(path) as f:
        for line in f:
            p = line.split()
            if len(p) == 3:
                out[int(p[0])].append((int(p[1], 16), p[2] == 't'))
    return out


def main():
    ap = argparse.ArgumentParser(prog='python3 -m recomp', description='Recompile a DS game to C.')
    ap.add_argument('rom')
    ap.add_argument('-o', '--out', required=True)
    ap.add_argument('--extra', help='entry points to add (the runtime\'s missing.txt)')
    ap.add_argument('--no-overlays', action='store_true')
    ap.add_argument('--build', action='store_true', help='run make afterwards')
    args = ap.parse_args()
    try:
        rom = Rom.load(args.rom)
    except RomError as e:
        sys.exit(f'{args.rom}: {e}')
    h = rom.header
    print(f'{rom.title} ({rom.gamecode}), ARM9 {len(rom.arm9):#x} bytes{" (was BLZ-compressed)" if rom.arm9_compressed else ""}, '
          f'{len(rom.autoloads)} autoload segment(s), {len(rom.overlays9)} ARM9 and {len(rom.overlays7)} ARM7 overlays')
    gen = os.path.join(args.out, 'gen')
    os.makedirs(gen, exist_ok=True)
    for f in os.listdir(gen):
        if f.endswith('.c') or f.endswith('.o'):
            os.remove(os.path.join(gen, f))
    extra = read_extra(args.extra)
    for cpu, arch, prefix in ((9, 5, 'g9'), (7, 4, 'g7')):
        segs = [(s.name, s.addr, s.data, s.kind) for s in rom.segments(cpu, overlays=not args.no_overlays)]
        pic = [(s.name, s.data) for s in rom.pic_stubs.get(cpu, [])]
        prog = Program(segs, arch=arch, prefix=prefix, pic=pic)
        entries = [(h[f'arm{cpu}_entry'], False)] + extra[cpu]
        prog.discover(entries)
        prog.emit(gen)
        st = prog.stats()
        print(f'ARM{cpu}: {st["functions"]} functions, {st["instructions"]} instructions, {len(prog.warnings)} warnings')
        for w in prog.warnings[:10]:
            print(f'    {w}')
    with open(os.path.join(args.out, 'arm9.bin'), 'wb') as f:
        f.write(rom.arm9)
    with open(os.path.join(args.out, 'Makefile'), 'w') as f:
        f.write(MAKEFILE.format(rt=os.path.join(ROOT, 'runtime')))
    if args.build:
        subprocess.run(['make', '-C', args.out, f'-j{os.cpu_count() or 2}', '--no-print-directory'], check=True)
        print(f'built {os.path.join(args.out, "dsn_headless")}')


if __name__ == '__main__':
    main()
